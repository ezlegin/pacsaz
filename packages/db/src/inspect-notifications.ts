import { prisma } from "./lib/prisma";

/**
 * Read-only view of the state the notification jobs act on.
 *
 * Used before and after a manual `/api/cron` run: the job summary tells you what
 * it decided, this tells you what the database actually contains. Writes nothing.
 *
 * Usage: pnpm --filter @repo/db exec tsx src/inspect-notifications.ts
 */
const main = async () => {
  const now = new Date();
  const windowEnd = new Date(now.getTime() + 48 * 60 * 60 * 1000);

  const [
    users,
    usersWithEmail,
    activePlans,
    expiringSoon,
    nearingQuota,
    campaignCoupons,
    notifications,
  ] = await Promise.all([
    prisma.user.count(),
    prisma.user.count({ where: { email: { not: "" } } }),
    prisma.plan.count({ where: { status: "active", endsAt: { gte: now } } }),
    prisma.plan.count({
      where: { status: "active", endsAt: { gte: now, lte: windowEnd } },
    }),
    prisma.plan.count({
      where: {
        status: "active",
        endsAt: { gte: now },
        fairDownload: { gt: 0, lte: 2 },
      },
    }),
    prisma.coupon.findMany({
      where: { source: "autoGenerated" },
      orderBy: { createdAt: "desc" },
      take: 5,
    }),
    prisma.notificationLog.groupBy({
      by: ["type", "status"],
      _count: { _all: true },
    }),
  ]);

  console.log(`now                       ${now.toISOString()}`);
  console.log(`users                     ${users}`);
  console.log(`users with an email       ${usersWithEmail}`);
  console.log(`active plans              ${activePlans}`);
  console.log(`expiring within 48h       ${expiringSoon}`);
  console.log(`plans near download quota ${nearingQuota} (approximate filter)`);

  console.log(`\ncampaign coupons (latest 5):`);
  if (campaignCoupons.length === 0) console.log("  none yet");
  for (const coupon of campaignCoupons) {
    console.log(
      `  ${coupon.campaign ?? "-"}  ${coupon.code}  ${coupon.amount}%  ` +
        `used=${coupon.used}/${coupon.limit ?? "-"}  expires=${coupon.expiresAt.toISOString().slice(0, 10)}`,
    );
  }

  console.log(`\nnotifications sent so far:`);
  if (notifications.length === 0) console.log("  none");
  for (const row of notifications) {
    console.log(`  ${row.type.padEnd(22)} ${row.status.padEnd(8)} ${row._count._all}`);
  }
};

main()
  .then(() => prisma.$disconnect())
  .catch(async (error) => {
    console.error(error);
    await prisma.$disconnect();
    process.exit(1);
  });

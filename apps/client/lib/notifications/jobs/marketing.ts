import { CouponSource, prisma } from "@repo/db";
import { notifyMarketing } from "../send";

/**
 * Monthly marketing campaign.
 *
 * Two steps, in this order, because the email has to quote real numbers:
 *   1. Mint the month's coupon (idempotent per campaign tag).
 *   2. Email every eligible user the code and its terms.
 *
 * Intended to be triggered by an external scheduler on the 1st of each month.
 * Running it again in the same month is harmless: step 1 finds the existing
 * coupon, and each user is deduped on `marketing:<campaign>`.
 */

/** Campaign tag format; also the coupon's unique `campaign` value. */
const CAMPAIGN_PREFIX = "PAC";

/** Coupon title used in the admin report. */
const DISCOUNT_RANGE = { min: 25, max: 45 } as const;

/** The coupon may be redeemed this many times in total. */
const USAGE_LIMIT = 10;

/** How long the code stays valid. */
const VALID_DAYS = 7;

/**
 * Recipients per run. Sending is sequential, so a large list would outlive the
 * serverless function limit; a truncated response tells the operator that the
 * job needs another trigger later in the month.
 */
const BATCH_SIZE = 150;

/**
 * Campaign tag for a month, e.g. `PAC-2026-10`.
 *
 * Uses UTC so the tag does not depend on the scheduler's timezone: running at
 * 00:05 on the 1st in Tehran must not produce the previous month's tag.
 */
export const campaignTagFor = (date: Date) => {
  const year = date.getUTCFullYear();
  const month = String(date.getUTCMonth() + 1).padStart(2, "0");
  return `${CAMPAIGN_PREFIX}-${year}-${month}`;
};

/**
 * A short, human-readable code. The randomness comes from the discount and the
 * secret suffix rather than a sequence, so codes are not guessable by
 * incrementing a number, while still being easy to read over the phone.
 */
const buildCode = (tag: string, percent: number) => {
  const suffix = Math.random().toString(36).slice(2, 6).toUpperCase();
  return `${tag.replace("PAC-", "")}-${percent}-${suffix}`;
};

const randomPercent = () =>
  Math.floor(
    Math.random() * (DISCOUNT_RANGE.max - DISCOUNT_RANGE.min + 1) +
      DISCOUNT_RANGE.min,
  );

export type MarketingCouponSummary = {
  campaign: string;
  code: string;
  percent: number;
  expiresAt: Date;
  limit: number;
  /** False when the coupon already existed, i.e. this run minted nothing. */
  created: boolean;
};

/**
 * Returns this month's coupon, creating it on first call.
 *
 * `campaign` is unique in the schema, so even two concurrent runs cannot mint
 * two coupons for the same month: the loser of the race hits the constraint and
 * falls back to reading the winner's row.
 */
export const ensureMonthlyCoupon = async (
  now = new Date(),
): Promise<MarketingCouponSummary> => {
  const campaign = campaignTagFor(now);

  const existing = await prisma.coupon.findUnique({ where: { campaign } });
  if (existing) {
    return {
      campaign,
      code: existing.code,
      percent: existing.amount,
      expiresAt: existing.expiresAt,
      limit: existing.limit ?? USAGE_LIMIT,
      created: false,
    };
  }

  const percent = randomPercent();
  const expiresAt = new Date(now.getTime() + VALID_DAYS * 24 * 60 * 60 * 1000);

  try {
    const created = await prisma.coupon.create({
      data: {
        code: buildCode(campaign, percent),
        // `type` stays a pure discount-type field; `source` records that this
        // coupon was minted by the campaign rather than typed in by an admin.
        type: "percent",
        source: CouponSource.autoGenerated,
        campaign,
        amount: percent,
        limit: USAGE_LIMIT,
        expiresAt,
      },
    });

    return {
      campaign,
      code: created.code,
      percent: created.amount,
      expiresAt: created.expiresAt,
      limit: created.limit ?? USAGE_LIMIT,
      created: true,
    };
  } catch (error) {
    // Lost the race against a concurrent run: use the coupon it created.
    if ((error as { code?: string }).code === "P2002") {
      const winner = await prisma.coupon.findUnique({ where: { campaign } });
      if (winner) {
        return {
          campaign,
          code: winner.code,
          percent: winner.amount,
          expiresAt: winner.expiresAt,
          limit: winner.limit ?? USAGE_LIMIT,
          created: false,
        };
      }
    }
    throw error;
  }
};

export type MarketingJobSummary = {
  campaign: string;
  code: string;
  percent: number;
  expiresAt: Date;
  limit: number;
  couponCreated: boolean;
  /** Users that matched the eligibility filter. */
  eligible: number;
  attempted: number;
  sent: number;
  skipped: number;
  failed: number;
  truncated: boolean;
};

export const runMonthlyMarketing = async (
  now = new Date(),
): Promise<MarketingJobSummary> => {
  const coupon = await ensureMonthlyCoupon(now);

  // Only reachable addresses; an onboarded user always has one, because the
  // onboarding form requires it.
  const where = { email: { not: "" } };

  const eligible = await prisma.user.count({ where });

  const recipients = await prisma.user.findMany({
    where,
    orderBy: { id: "asc" },
    take: BATCH_SIZE,
    select: { id: true, email: true, fullName: true },
  });

  const summary: MarketingJobSummary = {
    campaign: coupon.campaign,
    code: coupon.code,
    percent: coupon.percent,
    expiresAt: coupon.expiresAt,
    limit: coupon.limit,
    couponCreated: coupon.created,
    eligible,
    attempted: recipients.length,
    sent: 0,
    skipped: 0,
    failed: 0,
    truncated: eligible > recipients.length,
  };

  for (const user of recipients) {
    const result = await notifyMarketing({
      userId: user.id,
      email: user.email,
      fullName: user.fullName,
      code: coupon.code,
      percent: coupon.percent,
      expiresAt: coupon.expiresAt,
      limit: coupon.limit,
      campaign: coupon.campaign,
    });

    if (result.status === "sent") summary.sent += 1;
    else if (result.status === "failed") summary.failed += 1;
    else summary.skipped += 1;
  }

  return summary;
};

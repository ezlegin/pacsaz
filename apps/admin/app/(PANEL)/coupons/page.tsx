import { CouponForm } from "@/components/forms/CouponForm";
import Filter from "@/components/Filter";
import Pagination from "@/components/Pagination";
import PopupNewDialog from "@/components/PopupNewDialog";
import Search from "@/components/Search";
import { contains, pick, searchText } from "@/lib/listQuery";
import { Prisma, prisma } from "@repo/db";
import { globalPageSize } from "@repo/lib/data/consts";
import { pagination } from "@repo/lib/utils/pagination";
import { DialogTitle } from "@repo/ui/components/dialog";
import { Ticket } from "lucide-react";
import { Page, PageHeader } from "../components/PanelUI";
import CouponsList from "./CouponsList";

interface Props {
  searchParams: Promise<{ page?: string; search?: string; source?: string }>;
}

const page = async ({ searchParams }: Props) => {
  const { page, search, source } = await searchParams;
  const { skip, take } = pagination(page ?? "", globalPageSize);
  const q = searchText(search);
  const from = pick(source, ["manual", "autoGenerated"] as const);

  const where: Prisma.CouponWhereInput = {
    ...(q ? { code: contains(q) } : {}),
    ...(from ? { source: from } : {}),
  };

  const [coupons, total, tarrif] = await Promise.all([
    prisma.coupon.findMany({
      where,
      include: { tarrif: true },
      orderBy: { createdAt: "desc" },
      skip,
      take,
    }),
    prisma.coupon.count({ where }),
    prisma.tarrif.findMany(),
  ]);

  return (
    <Page>
      <PageHeader
        icon={Ticket}
        title="Coupons"
        description="Discount codes. A limit of 0 means unlimited; no plans ticked means the coupon fits every plan."
        actions={
          <PopupNewDialog buttonTitle="New coupon">
            <DialogTitle>New coupon</DialogTitle>
            <CouponForm tarrif={tarrif} />
          </PopupNewDialog>
        }
      />

      <div className="flex flex-wrap items-center gap-3">
        <Search placeholder="Search code" className="w-64" />
        <Filter
          name="source"
          placeholder="All sources"
          options={[
            { label: "Made by hand", value: "manual" },
            { label: "Marketing job", value: "autoGenerated" },
          ]}
        />
      </div>

      <CouponsList data={coupons} tarrif={tarrif} />

      <Pagination pageSize={globalPageSize} totalItems={total} />
    </Page>
  );
};

export default page;

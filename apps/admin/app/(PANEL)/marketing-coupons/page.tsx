import PageTitle from "@/components/PageTitle";
import { CouponSource, prisma } from "@repo/db";
import Card from "@repo/ui/components/custom/Card";
import { differenceInCalendarDays } from "date-fns";
import CampaignsList from "./CampaignsList";

/**
 * Campaign coupon report.
 *
 * Kept separate from `/coupons` on purpose. That page is a workbench: an admin
 * creates, edits and deletes coupons there. This page is a record: the coupons
 * are minted by the monthly marketing cron job and are read-only here, so the
 * numbers always describe what users actually received.
 */
/**
 * Read live data on every request.
 *
 * Without this the page has nothing dynamic about it, so Next.js prerenders it at
 * build time: not only would newly minted campaign coupons be missing, the
 * active/expired split below would be frozen against the build's clock.
 */
export const dynamic = "force-dynamic";

const Page = async () => {
  // A single instant for the whole render, so two rows cannot be classified
  // against different clock readings and disagree about the same date.
  const now = new Date();

  const coupons = await prisma.coupon.findMany({
    where: { source: CouponSource.autoGenerated },
    orderBy: { createdAt: "desc" },
  });

  const active = coupons.filter(
    (coupon) =>
      coupon.expiresAt.getTime() > now.getTime() &&
      (coupon.limit === null || coupon.used < coupon.limit),
  );

  const totalRedemptions = coupons.reduce((sum, coupon) => sum + coupon.used, 0);
  const averagePercent = coupons.length
    ? Math.round(
        coupons.reduce((sum, coupon) => sum + coupon.amount, 0) / coupons.length,
      )
    : 0;

  const latest = coupons[0];
  const latestDaysLeft = latest
    ? differenceInCalendarDays(latest.expiresAt, now)
    : null;

  const stats = [
    { label: "Campaigns", value: coupons.length, primaryTheme: true },
    { label: "Active now", value: active.length },
    { label: "Total redemptions", value: totalRedemptions },
    { label: "Average discount", value: `${averagePercent}%` },
  ];

  return (
    <div className="space-y-6">
      <PageTitle title="Marketing Coupons" />

      <div className="grid grid-cols-4 gap-5">
        {stats.map((stat) => (
          <Card
            key={stat.label}
            primaryTheme={stat.primaryTheme}
            className="flex justify-between items-center text-sm py-4"
          >
            <span className="text-base font-medium">{stat.label}</span>
            <span className="font-semibold">{stat.value}</span>
          </Card>
        ))}
      </div>

      <Card className="space-y-2 text-sm leading-relaxed text-muted-foreground">
        <p>
          A new coupon is minted automatically at the start of each month by the
          marketing job, with a random 25–45% discount, a 10-redemption limit and
          a 7-day validity, then emailed to every user with an address on file.
        </p>
        <p>
          These rows are read-only: they are the record of what was emailed, so
          editing one would make the email that quoted it inaccurate, and
          deleting one would break the link between an email and its code.
          Create ad-hoc coupons from the{" "}
          <span className="font-medium text-foreground">Coupons</span> page.
        </p>
        {latest && latestDaysLeft !== null && (
          <p className="text-foreground">
            Latest campaign{" "}
            <span className="font-medium" dir="ltr">
              {latest.code}
            </span>{" "}
            {latestDaysLeft >= 0
              ? `expires in ${latestDaysLeft} day(s).`
              : `expired ${Math.abs(latestDaysLeft)} day(s) ago.`}
          </p>
        )}
      </Card>

      <CampaignsList data={coupons} now={now} />
    </div>
  );
};

export default Page;
